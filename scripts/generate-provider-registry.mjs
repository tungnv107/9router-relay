import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const directory = new URL("../open-sse/providers/registry/", import.meta.url);
// Upstream intentionally hides these providers; regeneration must not enable them.
const excluded = new Set(["index.js", "REGISTRY_TEMPLATE.js", "trae.js", "devin-cli.js", "windsurf.js"]);
const available = readdirSync(directory).filter(name => name.endsWith(".js") && !excluded.has(name)).sort();
const previous = readFileSync(new URL("index.js", directory), "utf8");
const imports = new Map([...previous.matchAll(/^import (\w+) from "\.\/([^"/]+)";/gm)].map(match => [match[1], match[2]]));
const array = previous.match(/export default \[([\s\S]*?)\];/)[1];
const entries = [...array.matchAll(/^\s*(\w+),\s*$/gm)].map(match => [match[1], imports.get(match[1])]).filter(([, name]) => available.includes(name));
const registered = new Set(entries.map(([, name]) => name));
for (const name of available) {
  if (!registered.has(name)) entries.push([`registry${entries.length}`, name]);
}
const source = "// Auto-generated by scripts/generate-provider-registry.mjs\n" +
  entries.map(([alias, name]) => `import ${alias} from ${JSON.stringify("./" + name)};`).join("\n") +
  "\nexport default [\n" + entries.map(([alias]) => `  ${alias},`).join("\n") + "\n];\n";
writeFileSync(new URL("index.js", directory), source);
console.log(`Registered ${entries.length} providers`);
